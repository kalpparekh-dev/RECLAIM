# RECOVERY EFFECT
# ======================================================================

def calculate_recovery_effect(experiment):
    section("OBSERVED RECOVERY EFFECT")

    treatment = experiment[
        experiment["treatment"] == 1
    ]

    control = experiment[
        experiment["treatment"] == 0
    ]

    treatment_rate = treatment["recovered"].mean()
    control_rate = control["recovered"].mean()

    lift = treatment_rate - control_rate

    print(
        f"Treatment recovery rate: "
        f"{pct(treatment_rate)}"
    )

    print(
        f"Control recovery rate:   "
        f"{pct(control_rate)}"
    )

    print(
        f"Observed recovery lift:  "
        f"{lift:+.2%}"
    )

    print(
        f"Observed recovery lift:  "
        f"{lift * 100:+.2f} percentage points"
    )

    return treatment_rate, control_rate, lift


