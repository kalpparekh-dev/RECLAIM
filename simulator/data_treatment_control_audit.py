def validate_prediction_data(predictions):
    section("PREDICTION DATA STRUCTURE")

    print("Prediction columns:")
    print(list(predictions.columns))

    required = [
        "transaction_id",
        "amount",
    ]

    missing = [c for c in required if c not in predictions.columns]

    if missing:
        failed(
            f"Prediction dataset missing required columns: {missing}"
        )
        sys.exit(1)

    passed("Required prediction columns present")

    if predictions["transaction_id"].duplicated().any():
        failed("Prediction transaction IDs are not unique")
        sys.exit(1)

    passed("Prediction transaction IDs are unique")

    if not pd.to_numeric(
        predictions["amount"], errors="coerce"
    ).notna().all():
        failed("Prediction amounts contain invalid values")
        sys.exit(1)

    if (
        pd.to_numeric(predictions["amount"], errors="coerce") <= 0
    ).any():
        failed("Prediction amounts must be positive")
        sys.exit(1)

    passed("Prediction transaction amounts valid")

    probability_candidates = [
        "calibrated_probability",
        "recovery_probability",
        "base_recovery_probability",
    ]

    probability_column = None

    for column in probability_candidates:
        if column in predictions.columns:
            probability_column = column
            break

    if probability_column is None:
        warning("No recovery probability column found")
    else:
        probabilities = pd.to_numeric(
            predictions[probability_column],
            errors="coerce",
        )

        if probabilities.isna().any():
            failed(
                f"Probability column `{probability_column}` "
                "contains invalid values"
            )
            sys.exit(1)

        if ((probabilities < 0) | (probabilities > 1)).any():
            failed(
                f"Probability column `{probability_column}` "
                "contains values outside [0, 1]"
            )
            sys.exit(1)

        passed(
            f"Recovery probability column valid: "
            f"`{probability_column}`"
        )

    return probability_column


