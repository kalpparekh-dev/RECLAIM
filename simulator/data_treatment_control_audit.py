# TREATMENT ASSIGNMENT TIMING
# ======================================================================

def validate_assignment_metadata(experiment):
    section("TREATMENT ASSIGNMENT TIMING")

    timing_candidates = [
        "treatment_assigned_before_outcome",
        "assignment_before_outcome",
        "treatment_assignment_before_outcome",
        "experiment_valid",
    ]

    available = [
        column
        for column in timing_candidates
        if column in experiment.columns
    ]

    if not available:
        warning(
            "No explicit assignment-timing metadata column found."
        )

        print(
            "The dataset structure is compatible with a randomized "
            "experiment, but timing cannot be independently proven "
            "from the CSV alone."
        )

        return False

    for column in available:
        values = experiment[column]

        normalized = (
            values.astype(str)
            .str.strip()
            .str.lower()
        )

        true_values = {
            "true",
            "1",
            "yes",
            "y",
            "pass",
            "passed",
        }

        if normalized.isin(true_values).all():
            passed(
                f"`{column}` confirms assignment occurred "
                "before outcome generation"
            )
            return True

    warning(
        "Assignment timing metadata exists but does not "
        "confirm pre-outcome assignment."
    )

    return False


