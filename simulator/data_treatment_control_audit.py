def locate_files():
    header("LOCATING DATA")

    print(f"Project root: {PROJECT_ROOT}")

    if not PROJECT_ROOT.exists():
        failed(f"Project root does not exist: {PROJECT_ROOT}")
        sys.exit(1)

    if PREDICTION_FILE.exists():
        passed(f"Prediction dataset found: {PREDICTION_FILE}")
    else:
        failed(f"Prediction dataset missing: {PREDICTION_FILE}")
        sys.exit(1)

    # The experiment file is the PRIMARY source for this audit.
    if EXPERIMENT_FILE.exists():
        passed(
            f"Treatment/control experiment found: {EXPERIMENT_FILE}"
        )
    else:
        failed(
            "Treatment/control experiment file is missing:\n"
            f"{EXPERIMENT_FILE}"
        )

        print()
        print("Run the treatment/control experiment simulator first.")
        print(
            "The audit will NOT create treatment/control assignments "
            "itself."
        )

        sys.exit(1)

    # Legacy outcome file is optional.
    if OUTCOME_FILE.exists():
        passed(f"Legacy outcome dataset found: {OUTCOME_FILE}")
    else:
        warning(
            f"Legacy outcome dataset not found: {OUTCOME_FILE}"
        )

    return PREDICTION_FILE, EXPERIMENT_FILE


