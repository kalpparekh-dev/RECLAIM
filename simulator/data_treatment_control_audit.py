def load_data():
    prediction_file, experiment_file = locate_files()

    header("LOADING DATA")

    predictions = pd.read_csv(prediction_file)
    experiment = pd.read_csv(experiment_file)

    passed(f"Prediction rows: {len(predictions)}")
    passed(f"Experiment rows: {len(experiment)}")

    return predictions, experiment


