# SAVE AUDIT SUMMARY
# ======================================================================

def save_audit_summary(
    experiment,
    treatment_rate,
    control_rate,
    recovery_lift,
    incremental_net_value,
    ready,
):
    output_file = DATA_DIR / "treatment_control_audit_summary.csv"

    treatment = experiment[
        experiment["treatment"] == 1
    ]

    control = experiment[
        experiment["treatment"] == 0
    ]

    summary = pd.DataFrame(
        [
            {
                "total_transactions": len(experiment),
                "treatment_rows": len(treatment),
                "control_rows": len(control),
                "treatment_rate": treatment.mean().get(
                    "recovered", np.nan
                )
                if False
                else len(treatment) / len(experiment),
                "treatment_recovery_rate": treatment_rate,
                "control_recovery_rate": control_rate,
                "observed_recovery_lift": recovery_lift,
                "treatment_recovered_value":
                    treatment["recovered_amount"].sum(),
                "control_recovered_value":
                    control["recovered_amount"].sum(),
                "treatment_net_value":
                    treatment["net_recovered_value"].sum(),
                "control_net_value":
                    control["net_recovered_value"].sum(),
                "incremental_net_value_per_transaction":
                    incremental_net_value,
                "uplift_ready": ready,
            }
        ]
    )

    summary.to_csv(
        output_file,
        index=False,
    )

    passed(
        f"Saved audit summary: {output_file}"
    )


