def validate_transaction_ids(predictions, experiment):
    section("TRANSACTION POPULATION VALIDATION")

    prediction_ids = set(
        predictions["transaction_id"].astype(str)
    )

    experiment_ids = set(
        experiment["transaction_id"].astype(str)
    )

    missing_in_experiment = prediction_ids - experiment_ids
    extra_in_experiment = experiment_ids - prediction_ids

    print(f"Prediction population: {len(prediction_ids)}")
    print(f"Experiment population: {len(experiment_ids)}")
    print(
        f"Missing in experiment:  {len(missing_in_experiment)}"
    )
    print(
        f"Extra in experiment:    {len(extra_in_experiment)}"
    )

    if missing_in_experiment:
        failed(
            "Some prediction transactions are missing from "
            "the experiment dataset."
        )

        print(
            "First missing IDs:",
            list(missing_in_experiment)[:10]
        )

        sys.exit(1)

    if extra_in_experiment:
        warning(
            f"Experiment contains {len(extra_in_experiment)} "
            "transactions not present in predictions."
        )

        # This is not automatically fatal.
        # The experiment can be restricted to the prediction population.
        experiment = experiment[
            experiment["transaction_id"]
            .astype(str)
            .isin(prediction_ids)
        ].copy()

        passed(
            "Experiment population restricted to prediction population"
        )
    else:
        passed("Same transaction population")

    return experiment


