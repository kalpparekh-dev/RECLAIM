def header(title):
    print()
    print("=" * 70)
    print(title)
    print("=" * 70)


def section(title):
    print()
    print("=" * 70)
    print(title)
    print("=" * 70)


def passed(message):
    print(f"[PASS] {message}")


def warning(message):
    print(f"[WARN] {message}")


def failed(message):
    print(f"[FAIL] {message}")


def info(message):
    print(message)


def currency(value):
    if pd.isna(value):
        return "₹0.00"
    return f"₹{float(value):,.2f}"


def pct(value):
    if pd.isna(value):
        return "N/A"
    return f"{float(value):.2%}"


