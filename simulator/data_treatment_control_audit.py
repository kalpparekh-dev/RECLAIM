# FINAL READINESS DECISION
# ======================================================================

def final_readiness_decision(
    experiment,
    timing_verified,
):
    section("FINAL UPLIFT DATA READINESS DECISION")

    treatment = experiment["treatment"]

    treatment_count = int((treatment == 1).sum())
    control_count = int((treatment == 0).sum())

    required_columns = [
        "transaction_id",
        "treatment",
        "recovered",
        "recovered_amount",
        "intervention_cost",
        "customer_friction_cost",
        "net_recovered_value",
    ]

    all_required = all(
        column in experiment.columns
        for column in required_columns
    )

    unique_ids = (
        experiment["transaction_id"].is_unique
    )

    valid_treatment = set(
        pd.to_numeric(
            experiment["treatment"],
            errors="coerce",
        ).dropna().unique()
    ).issubset({0, 1})

    both_groups = (
        treatment_count > 0
        and control_count > 0
    )

    if all_required:
        passed("Required causal experiment columns present")
    else:
        failed(
            "Required causal experiment columns missing"
        )

    if unique_ids:
        passed("Transaction IDs unique")
    else:
        failed("Transaction IDs are not unique")

    if valid_treatment:
        passed("Treatment values are valid")
    else:
        failed("Treatment values are invalid")

    if both_groups:
        passed("Treatment and control groups both present")
    else:
        failed("Treatment/control groups incomplete")

    if timing_verified:
        passed(
            "Treatment assignment timing explicitly verified"
        )
    else:
        warning(
            "Treatment assignment timing is not explicitly "
            "verified from metadata."
        )

    print()
    print("-" * 70)

    # IMPORTANT:
    #
    # We should NOT make timing metadata a hard requirement because
    # the simulator itself generated this dataset. The audit can verify
    # the structural properties while warning if metadata is absent.

    ready = (
        all_required
        and unique_ids
        and valid_treatment
        and both_groups
        and len(experiment) >= 100
    )

    if ready:
        print(
            "[PASS] Valid treatment/control experiment detected."
        )

        print()
        print(
            "The dataset is suitable for causal uplift modeling."
        )

        print()
        print(
            "UPLIFT READINESS: READY"
        )
    else:
        print(
            "[WARN] Treatment/control experiment is not "
            "sufficient for causal uplift modeling."
        )

        print()
        print(
            "UPLIFT READINESS: NOT READY"
        )

    return ready


