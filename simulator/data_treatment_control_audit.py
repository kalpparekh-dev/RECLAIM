def validate_outcomes(experiment):
    section("RECOVERY OUTCOME VALIDATION")

    numeric_columns = [
        "recovered",
        "recovered_amount",
        "intervention_cost",
        "customer_friction_cost",
        "net_recovered_value",
    ]

    for column in numeric_columns:
        values = pd.to_numeric(
            experiment[column],
            errors="coerce",
        )

        if values.isna().any():
            failed(
                f"`{column}` contains invalid/null values"
            )
            sys.exit(1)

        passed(f"`{column}` valid")

    recovered = pd.to_numeric(
        experiment["recovered"],
        errors="coerce",
    )

    if not set(recovered.unique()).issubset({0, 1}):
        failed(
            "`recovered` must contain only 0 and 1."
        )
        sys.exit(1)

    passed("Recovery flags valid")

    recovered_amount = pd.to_numeric(
        experiment["recovered_amount"],
        errors="coerce",
    )

    if (recovered_amount < 0).any():
        failed(
            "`recovered_amount` contains negative values"
        )
        sys.exit(1)

    passed("Recovered amounts valid")

    intervention_cost = pd.to_numeric(
        experiment["intervention_cost"],
        errors="coerce",
    )

    if (intervention_cost < 0).any():
        failed(
            "`intervention_cost` contains negative values"
        )
        sys.exit(1)

    passed("Intervention costs valid")

    friction = pd.to_numeric(
        experiment["customer_friction_cost"],
        errors="coerce",
    )

    if (friction < 0).any():
        failed(
            "`customer_friction_cost` contains negative values"
        )
        sys.exit(1)

    passed("Customer friction costs valid")

    # Check consistency between treatment and intervention cost.
    treatment = pd.to_numeric(
        experiment["treatment"],
        errors="coerce",
    )

    untreated_with_cost = experiment.loc[
        treatment == 0,
        "intervention_cost"
    ]

    if (untreated_with_cost > 1e-9).any():
        warning(
            "Some control rows contain intervention cost."
        )
    else:
        passed(
            "Control rows have zero intervention cost"
        )

    treated_without_cost = experiment.loc[
        treatment == 1,
        "intervention_cost"
    ]

    if (treated_without_cost <= 0).any():
        warning(
            "Some treatment rows have zero intervention cost."
        )
    else:
        passed(
            "Treatment rows have positive intervention cost"
        )


