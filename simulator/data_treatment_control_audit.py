def validate_treatment(experiment):
    section("TREATMENT / CONTROL VALIDATION")

    treatment = pd.to_numeric(
        experiment["treatment"],
        errors="coerce",
    )

    if treatment.isna().any():
        failed("Treatment column contains null/invalid values")
        sys.exit(1)

    unique_values = sorted(treatment.unique().tolist())

    print(f"Treatment values detected: {unique_values}")

    if not set(unique_values).issubset({0, 1}):
        failed(
            "Treatment column must contain only 0 and 1."
        )
        sys.exit(1)

    passed("Treatment values valid")

    treatment_count = int((treatment == 1).sum())
    control_count = int((treatment == 0).sum())

    print()
    print(f"Treatment rows: {treatment_count}")
    print(f"Control rows:   {control_count}")

    if treatment_count == 0:
        failed("No treatment rows found")
        sys.exit(1)

    if control_count == 0:
        failed("No control rows found")
        sys.exit(1)

    passed("Both treatment and control groups present")

    rate = treatment.mean()

    print(f"Treatment allocation: {rate:.2%}")

    if rate < 0.05 or rate > 0.95:
        warning(
            "Treatment allocation is highly imbalanced."
        )
    else:
        passed("Treatment/control allocation is usable")

    return treatment


