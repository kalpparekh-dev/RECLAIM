def balance_check(experiment):
    section("TREATMENT / CONTROL BALANCE CHECK")

    treatment = experiment[
        experiment["treatment"] == 1
    ].copy()

    control = experiment[
        experiment["treatment"] == 0
    ].copy()

    balance_features = [
        "amount",
        "recovery_probability",
        "calibrated_probability",
        "confidence",
        "base_recovery_probability",
        "recoverability_score",
    ]

    available = [
        feature
        for feature in balance_features
        if feature in experiment.columns
    ]

    if not available:
        warning(
            "No numeric balance features available."
        )
        return

    print(
        f"{'feature':<32}"
        f"{'treatment mean':>18}"
        f"{'control mean':>18}"
    )
    print("-" * 68)

    for feature in available:
        treatment_values = pd.to_numeric(
            treatment[feature],
            errors="coerce",
        )

        control_values = pd.to_numeric(
            control[feature],
            errors="coerce",
        )

        treatment_mean = treatment_values.mean()
        control_mean = control_values.mean()

        print(
            f"{feature:<32}"
            f"{treatment_mean:>18.4f}"
            f"{control_mean:>18.4f}"
        )

    passed(
        "Treatment/control balance information calculated"
    )


