# ECONOMIC EFFECT
# ======================================================================

def calculate_economic_effect(experiment):
    section("OBSERVED ECONOMIC EFFECT")

    treatment = experiment[
        experiment["treatment"] == 1
    ]

    control = experiment[
        experiment["treatment"] == 0
    ]

    treatment_recovered = treatment[
        "recovered_amount"
    ].sum()

    control_recovered = control[
        "recovered_amount"
    ].sum()

    treatment_cost = treatment[
        "intervention_cost"
    ].sum()

    treatment_friction = treatment[
        "customer_friction_cost"
    ].sum()

    treatment_net = treatment[
        "net_recovered_value"
    ].sum()

    control_net = control[
        "net_recovered_value"
    ].sum()

    treatment_mean_net = treatment_net / len(treatment)
    control_mean_net = control_net / len(control)

    incremental_per_transaction = (
        treatment_mean_net - control_mean_net
    )

    print(
        f"Treatment recovered value: "
        f"{currency(treatment_recovered)}"
    )

    print(
        f"Control recovered value:   "
        f"{currency(control_recovered)}"
    )

    print()

    print(
        f"Treatment intervention cost: "
        f"{currency(treatment_cost)}"
    )

    print(
        f"Treatment friction cost:     "
        f"{currency(treatment_friction)}"
    )

    print()

    print(
        f"Treatment net value: "
        f"{currency(treatment_net)}"
    )

    print(
        f"Control net value:   "
        f"{currency(control_net)}"
    )

    print()

    print(
        "Observed incremental net value / transaction: "
        f"{currency(incremental_per_transaction)}"
    )

    if incremental_per_transaction > 0:
        passed(
            "Treatment produces positive observed "
            "incremental economic value."
        )
    else:
        warning(
            "Treatment does NOT produce positive observed "
            "incremental economic value in this experiment."
        )

    return incremental_per_transaction


